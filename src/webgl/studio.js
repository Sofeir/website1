import { MeshBasicMaterial, SRGBColorSpace } from 'three';

/**
 * Студия: материалы корпуса, свет и материал экрана.
 *
 * Освещения у сцены нет совсем: ни источников, ни карты окружения, ни теней.
 * Корпус залит ровным цветом и выглядит одинаково с любого угла — ни бликов,
 * ни градиентов, ни светлых пятен при повороте.
 *
 * Корпус чёрный (#0a0b0c), фон страницы #141618 светлее его вдвое. Форму
 * держит постоянный рельеф граней и светлая нить по фаскам — он вморожен
 * в геометрию и при повороте не меняется.
 */

/**
 * Карта окружения сцене больше не нужна и намеренно отсутствует.
 *
 * Материалы плоские, но MeshBasicMaterial всё равно подхватывает
 * `scene.environment` как отражение: оставь мы карту — на корпусе снова
 * появились бы блики, зависящие от угла поворота. Возврат `null` отключает
 * отражения полностью и заодно снимает генерацию PMREM при запуске.
 */
export function createEnvironment() {
  return null;
}

/**
 * Материалы — плоские, без освещения.
 *
 * Каждая поверхность заливается ровно своим цветом и не зависит ни от угла
 * поворота, ни от положения источников: никаких бликов, градиентов и «пятен
 * света» по корпусу не появляется. Форма читается силуэтом и тем, что соседние
 * детали окрашены разными тонами — плита темнее корпуса, стекло темнее плиты,
 * накладки светлые.
 *
 * `toneMapped: false` обязателен: иначе ACES вытянул бы даже плоскую заливку и
 * тон на экране перестал бы совпадать с заданным.
 */
export function createMaterials() {
  // Рельеф (см. relief в models.js) есть только у корпусных материалов.
  // Акцент, металл и объектив — ровная заливка: иначе фаски выбеливали бы
  // зелёную оправу сканера и накладки.
  const body = (color) => new MeshBasicMaterial({ color, toneMapped: false, vertexColors: true });
  const flat = (color) => new MeshBasicMaterial({ color, toneMapped: false });

  const shell = body(0x0a0b0c);
  const shellMatte = body(0x08090a);
  const bezel = body(0x050606);
  const accent = flat(0x2fbf94);
  const lens = flat(0x020304);
  const metal = flat(0x4a5055);

  return { shell, shellMatte, bezel, accent, lens, metal };
}

/**
 * Экран не зависит от освещения: это источник изображения, а не поверхность.
 *
 * Фильтры текстуры здесь НЕ трогаем — они выставлены при загрузке (мипмапы и
 * анизотропия, см. screens.js). Раньше материал перетирал их на LinearFilter,
 * мипмапы отключались, и точечный растр логотипа на наклонённом экране
 * рассыпался — те самые «поплывшие кружочки».
 */
export function createScreenMaterial(texture) {
  const material = new MeshBasicMaterial({ map: texture, toneMapped: false });
  material.map.colorSpace = SRGBColorSpace;
  return material;
}

